#!/usr/bin/env python3
"""
Compare local migration files with the migration history of the linked Supabase project.

Usage:
    python3 scripts/check_migrations.py          # compare against the linked project
    python3 scripts/check_migrations.py --sql    # print the same check as SQL for the SQL Editor

Reports, and exits 1 on, any of:
    pending      local files not applied remotely yet
    remote-only  remote versions with no local file; `supabase db push` refuses to run
                 until the file is restored or the history is repaired
    duplicate    local files sharing a version; `supabase db push` fails on the
                 schema_migrations primary key

Requires (default mode):
    supabase CLI installed, logged in (`supabase login`), and linked (`supabase link`).
"""

import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

MIGRATIONS_DIR = Path(__file__).resolve().parent.parent / "supabase" / "migrations"
# Same file name pattern the supabase CLI uses; other files are ignored by it.
MIGRATION_FILE = re.compile(r"^([0-9]+)_.*\.sql$")
# Older CLI tables use "|", newer ones box-drawing "│".
CELL_SEPARATOR = re.compile(r"[|│]")
VERSION = re.compile(r"^[0-9]+$")


def local_migrations() -> dict[str, list[str]]:
    by_version: dict[str, list[str]] = defaultdict(list)
    for path in sorted(MIGRATIONS_DIR.iterdir()):
        match = MIGRATION_FILE.match(path.name)
        if match:
            by_version[match.group(1)].append(path.name)
    return by_version


def report_duplicates(by_version: dict[str, list[str]]) -> bool:
    duplicates = {v: names for v, names in by_version.items() if len(names) > 1}
    if duplicates:
        print("\nDuplicate local versions (delete or renumber all but one):", file=sys.stderr)
        for version, names in sorted(duplicates.items()):
            print(f"  {version}: {', '.join(names)}", file=sys.stderr)
    return bool(duplicates)


def parse_migration_list(output: str) -> tuple[list[str], list[str], list[str]]:
    """Split `supabase migration list` rows into (applied, pending, remote_only)."""
    applied: list[str] = []
    pending: list[str] = []
    remote_only: list[str] = []
    leading_border = False

    for raw_line in output.splitlines():
        line = raw_line.strip()
        if not CELL_SEPARATOR.search(line):
            continue
        cells = [cell.strip().strip("`").strip() for cell in CELL_SEPARATOR.split(line)]
        if "Local" in cells and "Remote" in cells:
            leading_border = cells[0] == ""
            continue
        if leading_border:
            cells = cells[1:]
        if len(cells) < 2:
            continue
        local, remote = cells[0], cells[1]
        # A blank Local cell is a remote-only row; it must not be skipped.
        if not (VERSION.match(local) or VERSION.match(remote)):
            continue
        if local and remote:
            applied.append(local)
        elif local:
            pending.append(local)
        else:
            remote_only.append(remote)

    return applied, pending, remote_only


def print_sql(by_version: dict[str, list[str]]) -> None:
    values = ",\n".join(
        f"    ('{version}', '{name.replace(chr(39), chr(39) * 2)}')"
        for version, names in sorted(by_version.items())
        for name in names
    )
    print(
        f"""-- Auto-generated by scripts/check_migrations.py --sql — do not edit by hand.
-- Run this in the Supabase SQL Editor to compare local migration files with the
-- remote migration history. Any status other than 'applied' needs attention.

WITH local_migrations(version, filename) AS (
  VALUES
{values}
)
SELECT
  COALESCE(lm.version, sm.version) AS version,
  lm.filename,
  CASE
    WHEN lm.version IS NULL THEN 'REMOTE ONLY - no local file'
    WHEN sm.version IS NULL THEN 'PENDING - needs to be run manually'
    ELSE 'applied'
  END AS status
FROM local_migrations lm
FULL OUTER JOIN supabase_migrations.schema_migrations sm
  ON sm.version = lm.version
ORDER BY 1;"""
    )


def main() -> None:
    by_version = local_migrations()

    if sys.argv[1:] == ["--sql"]:
        print_sql(by_version)
        sys.exit(1 if report_duplicates(by_version) else 0)
    if sys.argv[1:]:
        print(__doc__.strip(), file=sys.stderr)
        sys.exit(2)

    result = subprocess.run(
        ["supabase", "migration", "list", "--linked"],
        capture_output=True,
        text=True,
    )

    if result.returncode != 0:
        print(result.stderr.strip(), file=sys.stderr)
        sys.exit(1)

    applied, pending, remote_only = parse_migration_list(result.stdout)

    print(result.stdout)
    if not (applied or pending or remote_only) and by_version:
        print("Could not parse any rows from `supabase migration list`.", file=sys.stderr)
        sys.exit(1)

    print(f"Applied: {len(applied)}  Pending: {len(pending)}  Remote-only: {len(remote_only)}")

    if pending:
        print("\nPending migrations (in order):")
        for v in pending:
            print(f"  {v}")
    if remote_only:
        print("\nRemote-only versions (no local file; `supabase db push` will refuse to run):")
        for v in remote_only:
            print(f"  {v}")
    has_duplicates = report_duplicates(by_version)

    if pending or remote_only or has_duplicates:
        sys.exit(1)


if __name__ == "__main__":
    main()
